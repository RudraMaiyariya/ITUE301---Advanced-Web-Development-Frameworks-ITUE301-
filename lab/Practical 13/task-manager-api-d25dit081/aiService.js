// In-Memory Rate Limiting Tracker: userId -> lastRequestTimestamp
const rateLimitMap = new Map();
const RATE_LIMIT_WINDOW_MS = 60 * 1000; // 1 minute window

export function checkAiRateLimit(userId) {
    const now = Date.now();
    const lastRequest = rateLimitMap.get(userId);

    if (lastRequest && now - lastRequest < RATE_LIMIT_WINDOW_MS) {
        const remainingSeconds = Math.ceil((RATE_LIMIT_WINDOW_MS - (now - lastRequest)) / 1000);
        return {
            allowed: false,
            remainingSeconds,
            error: `Rate limit reached: Please wait ${remainingSeconds} seconds before requesting another AI generation.`
        };
    }

    rateLimitMap.set(userId, now);
    return { allowed: true };
}

/**
 * Intelligent Fallback Generator (Graceful Degradation Engine)
 * Generates context-aware task descriptions and priority when offline or third-party API fails.
 */
function generateContextualFallback(title) {
    const lower = title.toLowerCase();
    let description = '';
    let priority = 'medium';
    let deadline = '3 days';

    if (lower.includes('bug') || lower.includes('fix') || lower.includes('error') || lower.includes('issue')) {
        description = `Investigate root cause of "${title}". Reproduce issue locally, inspect server logs and error stack traces, apply bugfix, and verify with regression testing.`;
        priority = 'high';
        deadline = '1 day';
    } else if (lower.includes('deploy') || lower.includes('release') || lower.includes('docker') || lower.includes('ci')) {
        description = `Prepare deployment pipeline for "${title}". Verify build artifacts, run security audits, check environment variables, and monitor health post-release.`;
        priority = 'high';
        deadline = '2 days';
    } else if (lower.includes('design') || lower.includes('ui') || lower.includes('frontend') || lower.includes('css')) {
        description = `Design and implement UI components for "${title}". Ensure responsive layout across desktop and mobile, adhering to UX standards and accessibility guidelines.`;
        priority = 'medium';
        deadline = '4 days';
    } else if (lower.includes('test') || lower.includes('qa')) {
        description = `Write comprehensive automated test suites for "${title}". Cover edge cases, input validation, and assert expected status codes.`;
        priority = 'medium';
        deadline = '2 days';
    } else if (lower.includes('doc') || lower.includes('readme') || lower.includes('report')) {
        description = `Draft technical documentation for "${title}". Document API endpoints, payload schemas, setup commands, and architectural workflows.`;
        priority = 'low';
        deadline = '5 days';
    } else {
        description = `Plan and execute tasks related to "${title}". Break down into deliverable milestones, review requirements, and verify integration.`;
        priority = 'medium';
        deadline = '3 days';
    }

    return {
        description,
        suggestedPriority: priority,
        suggestedDeadline: deadline,
        fallback: true
    };
}

/**
 * Main AI Generation Function
 */
export async function generateTaskAiSuggestions(title) {
    const geminiKey = process.env.GEMINI_API_KEY || process.env.AI_API_KEY;

    // Supplementary Problem 3: Mandatory AI Disclaimer
    const disclaimer = '⚠️ AI Disclaimer: This content is generated by AI. Please review and verify accuracy before submitting.';

    // If API key is present, attempt remote API call with timeout
    if (geminiKey && geminiKey.trim() !== 'your_api_key_here') {
        try {
            const controller = new AbortController();
            const timeoutId = setTimeout(() => controller.abort(), 8000); // 8s timeout

            const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiKey}`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                signal: controller.signal,
                body: JSON.stringify({
                    contents: [{
                        parts: [{
                            text: `Generate a concise 2-sentence task description and suggest a priority (low, medium, high) for the task title: "${title}". Return JSON format: {"description": "...", "priority": "..."}`
                        }]
                    }]
                })
            });

            clearTimeout(timeoutId);

            if (response.ok) {
                const data = await response.json();
                const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text || '';
                const jsonMatch = rawText.match(/\{[\s\S]*\}/);
                if (jsonMatch) {
                    const parsed = JSON.parse(jsonMatch[0]);
                    return {
                        success: true,
                        title,
                        description: parsed.description,
                        suggestedPriority: parsed.priority || 'medium',
                        disclaimer,
                        fallback: false,
                        source: 'Google Gemini 1.5 Flash'
                    };
                }
            }
        } catch (err) {
            console.warn(`[AI Service] Remote API unavailable (${err.message}). Activating graceful degradation.`);
        }
    }

    // Graceful Degradation: return robust contextual fallback without breaking the app
    const fallbackData = generateContextualFallback(title);
    return {
        success: true,
        title,
        description: fallbackData.description,
        suggestedPriority: fallbackData.suggestedPriority,
        suggestedDeadline: fallbackData.suggestedDeadline,
        disclaimer,
        fallback: true,
        source: 'Contextual AI Assistant (Offline Graceful Degradation)'
    };
}
